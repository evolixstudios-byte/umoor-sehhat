
    CREATE TABLE IF NOT EXISTS staff (
      id TEXT PRIMARY KEY,
      name TEXT NOT NULL UNIQUE,
      pin_hash TEXT NOT NULL,
      pin_salt TEXT NOT NULL,
      counters TEXT NOT NULL DEFAULT '[]',
      can_register INTEGER DEFAULT 0,
      is_active INTEGER DEFAULT 1,
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL,
      last_login_at TEXT,
      login_count INTEGER DEFAULT 0
    );
    CREATE INDEX IF NOT EXISTS idx_staff_name ON staff(name);


    CREATE TABLE IF NOT EXISTS admin (
      id TEXT PRIMARY KEY,
      email TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      password_salt TEXT NOT NULL,
      must_change_password INTEGER DEFAULT 1,
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL,
      last_login_at TEXT
    );


    CREATE TABLE IF NOT EXISTS participants (
      id TEXT PRIMARY KEY,
      token INTEGER NOT NULL UNIQUE,
      serial TEXT NOT NULL UNIQUE,
      its TEXT NOT NULL UNIQUE,
      name TEXT NOT NULL,
      phone TEXT NOT NULL,
      age INTEGER NOT NULL,
      gender TEXT NOT NULL,
      consent INTEGER DEFAULT 1,
      registered_at TEXT NOT NULL,
      registered_by TEXT,
      bp_systolic INTEGER,
      bp_diastolic INTEGER,
      pulse_bpm INTEGER,
      bp_at TEXT,
      bp_by TEXT,
      blood_sugar REAL,
      sugar_type TEXT,
      sugar_at TEXT,
      sugar_by TEXT,
      height REAL,
      weight REAL,
      bmi REAL,
      measurements_at TEXT,
      measurements_by TEXT,
      advice TEXT,
      doctor_at TEXT,
      doctor_by TEXT,
      updated_at TEXT NOT NULL,
      sync_status TEXT DEFAULT 'pending',
      sync_error TEXT,
      last_synced_at TEXT
    );
    CREATE INDEX IF NOT EXISTS idx_participants_token ON participants(token);
    CREATE INDEX IF NOT EXISTS idx_participants_its ON participants(its);
    CREATE INDEX IF NOT EXISTS idx_participants_name ON participants(name);
    CREATE INDEX IF NOT EXISTS idx_participants_updated ON participants(updated_at);


    CREATE TABLE IF NOT EXISTS audit_logs (
      id TEXT PRIMARY KEY,
      timestamp TEXT NOT NULL,
      actor_type TEXT NOT NULL,
      actor_id TEXT NOT NULL,
      actor_name TEXT NOT NULL,
      actor_role TEXT NOT NULL,
      action TEXT NOT NULL,
      target_type TEXT,
      target_id TEXT,
      details TEXT,
      ip TEXT
    );
    CREATE INDEX IF NOT EXISTS idx_audit_timestamp ON audit_logs(timestamp);


    CREATE TABLE IF NOT EXISTS sync_queue (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      action TEXT NOT NULL,
      payload TEXT NOT NULL,
      status TEXT DEFAULT 'pending',
      retries INTEGER DEFAULT 0,
      error_message TEXT,
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS idx_sync_status ON sync_queue(status);


    CREATE TABLE IF NOT EXISTS token_sequence (
      id INTEGER PRIMARY KEY CHECK (id = 1),
      last_token INTEGER NOT NULL DEFAULT 0
    );


    CREATE TABLE IF NOT EXISTS idempotency_keys (
      key TEXT PRIMARY KEY,
      action TEXT NOT NULL,
      response_body TEXT NOT NULL,
      response_status INTEGER NOT NULL,
      created_at TEXT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS idx_idempotency_created ON idempotency_keys(created_at);

